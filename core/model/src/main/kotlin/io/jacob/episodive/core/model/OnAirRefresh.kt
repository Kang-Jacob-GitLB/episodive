package io.jacob.episodive.core.model

/** 지금 방송 중인 프로그램을 얼마나 자주 다시 확인할지. */
enum class OnAirRefresh {
    /** 편성표를 5분 TTL 마다 다시 받아 임시 편성 변경을 따라간다. 플레이어처럼 한 스테이션을 지켜보는 화면용이다. */
    Live,

    /**
     * 프로그램 경계(끝 시각)에만 다시 계산한다. 캐시에 지금 프로그램이 있으면 TTL 이 지났어도 그대로 쓰고, 없을 때만 받는다.
     * 여러 스테이션의 썸네일을 한꺼번에 그리는 목록용이다 — 임시 편성 변경이 늦게 반영되는 대신 요청이 크게 준다.
     */
    Boundary,
}
